"""One-time provenance script for the pulse-sequence diagrams: generate contrast/psd_constants.js and
contrast/psd_golden.json from the original Streamlit app (MRI_Simulator/app.py).

It evaluates the app's schematic-geometry constants (the block above draw_pulse_sequence) and runs the real
matplotlib draw_pulse_sequence over a spread of parameters, recording every line, text, arrow and rectangle of
each figure. The JS port (contrast/psd.js) must reproduce those records.

Run:   python <path>/gen_psd_from_python.py
"""
import ast
import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.colors  # noqa: E402
import matplotlib.patches as mpatches  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402
import matplotlib.transforms as mtransforms  # noqa: E402
import numpy as np  # noqa: E402
from matplotlib.text import Annotation  # noqa: E402

APP = r"C:\Dave\MRI_Simulator\app.py"
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

src = open(APP, encoding="utf-8").read()
tree = ast.parse(src)
ns = {"np": np, "plt": plt, "mtransforms": mtransforms, "mpatches": mpatches}

const_names = []
func = None
for node in tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
        name = node.targets[0].id
        if 370 <= node.lineno <= 650 or name in ("MPRAGE_TR_READOUT",):
            exec(compile(ast.Module([node], []), APP, "exec"), ns)
            const_names.append(name)
    elif isinstance(node, ast.FunctionDef) and node.name == "draw_pulse_sequence":
        func = node
assert func is not None
exec(compile(ast.Module([func], []), APP, "exec"), ns)
draw = ns["draw_pulse_sequence"]

# ---- constants for JS ----
with open(os.path.join(OUT_DIR, "psd_constants.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by tools/gen_psd_from_python.py from the original MRI_Simulator/app.py. Do not edit by hand.\n")
    f.write("// Schematic-geometry constants of the pulse-sequence diagrams (time in schematic units, amplitudes in row units).\n\n")
    for name in const_names:
        v = ns[name]
        if isinstance(v, (bool, int, float, str, tuple, list)):
            f.write(f"export const {name} = {json.dumps(list(v) if isinstance(v, tuple) else v, ensure_ascii=False)};\n")


# ---- recorder ----
_r = lambda v: round(float(v), 10)  # keeps the golden file small; the JS test tolerance is 1e-8

def rec_line(ax, ln):
    blended = type(ln.get_transform()).__name__ == "BlendedGenericTransform"
    return {"x": [_r(v) for v in ln.get_xdata()], "y": [_r(v) for v in ln.get_ydata()],
            "axv": blended, "color": ln.get_color(), "lw": float(ln.get_linewidth()),
            "ls": ln.get_linestyle(), "alpha": None if ln.get_alpha() is None else float(ln.get_alpha())}


def rec_text(t):
    if isinstance(t, Annotation):
        ap = t.arrowprops or {}
        return {"kind": "arrow", "xy": [_r(v) for v in t.xy], "xytext": [_r(v) for v in t.xyann],
                "color": ap.get("color"), "lw": float(ap.get("lw", 0)), "arrowstyle": ap.get("arrowstyle")}
    x, y = t.get_position()
    return {"kind": "text", "x": _r(x), "y": _r(y), "s": t.get_text(), "color": t.get_color(),
            "size": float(t.get_fontsize()), "ha": t.get_ha(), "va": t.get_va(),
            "weight": str(t.get_fontweight()), "style": t.get_fontstyle()}


def record(args):
    fig = draw(**args)
    if fig is None:
        return None
    out = {"figTexts": [rec_text(t) for t in fig.texts], "axes": [], "rects": []}
    for a in fig.artists:
        if isinstance(a, mpatches.Rectangle):
            out["rects"].append({"xy": [_r(v) for v in a.get_xy()], "w": float(a.get_width()), "h": float(a.get_height()),
                                 "edge": matplotlib.colors.to_hex(a.get_edgecolor()),
                                 "lw": float(a.get_linewidth()), "ls": a.get_linestyle()})
    for ax in fig.axes:
        out["axes"].append({"visible": bool(ax.get_visible()), "xlim": [_r(v) for v in ax.get_xlim()],
                            "ylim": [_r(v) for v in ax.get_ylim()],
                            "lines": [rec_line(ax, ln) for ln in ax.lines], "texts": [rec_text(t) for t in ax.texts]})
    plt.close(fig)
    return out


def case(seq, **kw):
    base = dict(seq=seq, TR=4000, TE=80, TI=0, FA=90, ETL=16, slice_mm=5, BW=200, FOV_read=240,
                epi_eff_idx=1, epi_n_readouts=64, TI2=0, Npartitions=176)
    base.update(kw)
    return base


cases = []
for TR, TE, ETL in [(4000, 80, 16), (4000, 30, 1), (4000, 100, 4), (4000, 150, 6), (4000, 200, 8), (300, 80, 16), (6000, 40, 32), (4000, 400, 4)]:
    cases.append(case("FSE", TR=TR, TE=TE, ETL=ETL))
for seq, trs, tis in (("FLAIR", (9000, 3500), (2500, 800, 100, 3500)), ("STIR", (3000, 1200), (210, 60, 400))):
    for TR in trs:
        for TI in tis:
            for TE, ETL in ((90, 16), (50, 4), (150, 8)):
                cases.append(case(seq, TR=TR, TI=TI, TE=TE, ETL=ETL))
cases.append(case("FLAIR", TR=1000, TI=2500, TE=90, ETL=16))
for TE in (2, 5, 7, 8, 20, 60, 100, 150):
    for FA, sl, BW, FOV in ((30, 5, 200, 240), (10, 1, 100, 180), (90, 10, 500, 400)):
        cases.append(case("GRE", TR=700, TE=TE, FA=FA, slice_mm=sl, BW=BW, FOV_read=FOV))
for TR, FA in ((5, 50), (3, 10), (20, 90)):
    cases.append(case("bSSFP", TR=TR, FA=FA, TE=TR / 2))
for TI, TI2 in ((3400, 800), (2500, 600), (3400, 200), (3400, 100), (1000, 3000), (3400, 30), (500, 100)):
    for TE, ETL in ((25, 8), (60, 4)):
        cases.append(case("DIR", TR=8000, TI=TI, TI2=TI2, TE=TE, ETL=ETL))
cases.append(case("DIR", TR=2000, TI=3400, TI2=800, TE=25, ETL=8))
for TR, TI, FA, N in ((2300, 900, 9, 176), (2300, 200, 5, 176), (6000, 2500, 15, 32), (2300, 900, 9, 4), (2300, 900, 9, 3), (2300, 900, 12, 256)):
    cases.append(case("MPRAGE", TR=TR, TI=TI, FA=FA, TE=3, Npartitions=N))
for TE, idx, n in ((30, 1, 64), (30, 37, 128), (5, 5, 64), (80, 63, 64), (3, 0, 64), (60, 8, 128), (30, 4, 256)):
    cases.append(case("EPI (single-shot)", TR=2000, TE=TE, epi_eff_idx=idx, epi_n_readouts=n))
cases.append(case("DWI"))  # no diagram

golden = []
for c in cases:
    golden.append({"args": c, "figure": record(c)})
with open(os.path.join(OUT_DIR, "psd_golden.json"), "w", encoding="utf-8", newline="\n") as f:
    json.dump(golden, f, separators=(",", ":"))
print(f"{len(const_names)} constants, {len(golden)} golden figures")
