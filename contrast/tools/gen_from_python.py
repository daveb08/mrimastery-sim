"""One-time provenance script: generate contrast/tables.js and contrast/golden.json from the
original Streamlit app (MRI_Simulator/app.py), so the JS port starts from exactly the same data and
is tested against the Python physics, including the app's own SNR-pipeline statements.

Run from the MRI_Simulator folder:   python <path>/gen_from_python.py
"""
import ast
import itertools
import json
import os
import sys

APP_DIR = r"C:\Dave\MRI_Simulator"
OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, APP_DIR)
os.chdir(APP_DIR)

import test_simulator as ts  # noqa: E402  (loads the app's physics via ast, no Streamlit)

phys = ts._physics
APP = os.path.join(APP_DIR, "app.py")

# ---- tables: literal-evaluate the dictionaries straight out of app.py ----
tree = ast.parse(open(APP, encoding="utf-8").read())
WANT = ["TISSUES", "FIELD_STRENGTH_TISSUES", "FIELD_SNR_SCALE", "TR_MAX_BY_FIELD", "PROTOCOL_PRESETS"]
tables = {}
for node in tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) \
            and node.targets[0].id in WANT:
        tables[node.targets[0].id] = ast.literal_eval(node.value)
assert set(tables) == set(WANT), set(WANT) - set(tables)

with open(os.path.join(OUT_DIR, "tables.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by tools/gen_from_python.py from the original MRI_Simulator/app.py. Do not edit by hand.\n")
    f.write("// Base tissue properties (PD, ADC, colour), the per-field-strength T1/T2/T2*, SNR scaling,\n")
    f.write("// maximum TR per field, and the teaching protocol presets.\n\n")
    names = {"TISSUES": "TISSUES_BASE"}
    for key in WANT:
        f.write(f"export const {names.get(key, key)} = {json.dumps(tables[key], indent=2, ensure_ascii=False)};\n\n")

# ---- golden values ----
T = tables["FIELD_STRENGTH_TISSUES"]
BASE = tables["TISSUES"]
golden = {"signals": [], "helpers": [], "scanTime": [], "pipeline": []}


def tissue(field, name):
    return {**BASE[name], **T[field][name]}


def add(fn, args, value):
    golden["signals"].append({"fn": fn, "args": args, "value": float(value)})


for field in ("0.064T", "1.5T", "3.0T", "7.0T"):
    for name in ("WM", "GM", "CSF", "Fat"):
        t = tissue(field, name)
        fat = name == "Fat"
        for TR, TE in itertools.product((500, 2000, 6000), (10, 80, 150)):
            for fs in (False, True):
                add("fse", [TR, TE, t["T1"], t["T2"], t["PD"], fs, fat],
                    phys["fse_signal"](TR, TE, t["T1"], t["T2"], t["PD"], fs, fat))
        for TR, TE, FA in itertools.product((5, 100, 700, 3000), (2, 10, 25), (5, 30, 90)):
            for fs in (False, True):
                add("gre", [TR, TE, FA, t["T1"], t["T2s"], t["PD"], fs, fat],
                    phys["gre_signal"](TR, TE, FA, t["T1"], t["T2s"], t["PD"], fs, fat))
        for TR, TI, TE in itertools.product((3000, 9000), (150, 210, 900, 2500), (25, 90)):
            for fs in (False, True):
                add("flair", [TR, TI, TE, t["T1"], t["T2"], t["PD"], fs, fat],
                    phys["flair_signal"](TR, TI, TE, t["T1"], t["T2"], t["PD"], fs, fat))
        for TR, FA in itertools.product((3, 5, 10, 20), (10, 50, 90)):
            add("bssfp", [TR, FA, t["T1"], t["T2"], t["PD"]],
                phys["bssfp_signal"](TR, FA, t["T1"], t["T2"], t["PD"]))
        for TR, TI1, TI2, TE in itertools.product((5000, 8000), (2500, 3400), (400, 800, 1500), (25, 80)):
            add("dir", [TR, TI1, TI2, TE, t["T1"], t["T2"], t["PD"]],
                phys["dir_signal"](TR, TI1, TI2, TE, t["T1"], t["T2"], t["PD"]))
        for TR, TE, b in itertools.product((3000, 5000), (50, 80, 150), (0, 500, 1000, 3000)):
            add("dwi", [TR, TE, b, t["T1"], t["T2"], t["PD"], t["ADC"]],
                phys["dwi_signal"](TR, TE, b, t["T1"], t["T2"], t["PD"], t["ADC"]))
        for TR, TI, TE, FA in itertools.product((2000, 2300), (200, 900, 2500), (2, 3, 18), (5, 9, 15)):
            add("mprage", [TR, TI, TE, FA, t["T1"], t["T2s"], t["PD"]],
                phys["mprage_signal"](TR, TI, TE, FA, t["T1"], t["T2s"], t["PD"]))
        for TR, TE in itertools.product((500, 2000, 3000), (1, 30, 100)):
            add("epi", [TR, TE, t["T1"], t["T2s"], t["PD"]], phys["epi_signal"](TR, TE, t["T1"], t["T2s"], t["PD"]))
        for TR in (500, 3000, 9000):
            golden["helpers"].append({"fn": "csfNullTi", "args": [TR, t["T1"]], "value": float(phys["csf_null_ti"](TR, t["T1"]))})
            golden["helpers"].append({"fn": "ernstAngle", "args": [TR, t["T1"]], "value": float(phys["ernst_angle"](TR, t["T1"]))})
        for TR in (3, 5, 10):
            golden["helpers"].append({"fn": "bssfpOptimalFa", "args": [TR, t["T1"], t["T2"]],
                                      "value": float(phys["bssfp_optimal_fa"](TR, t["T1"], t["T2"]))})
        for TR, TI1 in itertools.product((5000, 8000, 12000), (2000, 3400, 4500)):
            v = phys["dir_null_ti2"](TR, TI1, t["T1"])
            golden["helpers"].append({"fn": "dirNullTi2", "args": [TR, TI1, t["T1"]], "value": None if v is None else float(v)})

for seq, TR, phase, etl, nex, nparts in [
        ("GRE", 700, 192, 1, 1, 1), ("GRE", 5, 256, 1, 2, 1), ("MPRAGE", 2300, 256, 1, 1, 176),
        ("FSE", 4000, 256, 16, 1, 1), ("FSE", 600, 256, 4, 2, 1), ("FLAIR", 9000, 256, 16, 1, 1),
        ("STIR", 3000, 224, 8, 1, 1), ("bSSFP", 5, 256, 1, 1, 1), ("DIR", 8000, 256, 8, 1, 1),
        ("DWI", 5000, 128, 1, 2, 1), ("EPI (single-shot)", 2000, 128, 128, 1, 1)]:
    golden["scanTime"].append({"args": [TR, phase, etl, nex, seq, nparts],
                               "value": float(phys["calc_scan_time"](TR, phase, etl, nex, seq, nparts))})

# ---- pipeline golden: the app's own SNR statements, run on full parameter sets ----
pipeline = ts._SNR_PIPELINE


def base_signals(seq, field, q):
    out = {}
    for name in ("WM", "GM", "CSF", "Fat"):
        t, fat = tissue(field, name), name == "Fat"
        fs = q["fatSat"]
        if seq == "FSE":
            s = phys["fse_signal"](q["TR"], q["TE"], t["T1"], t["T2"], t["PD"], fs, fat)
        elif seq == "GRE":
            s = phys["gre_signal"](q["TR"], q["TE"], q["FA"], t["T1"], t["T2s"], t["PD"], fs, fat)
        elif seq in ("FLAIR", "STIR"):
            s = phys["flair_signal"](q["TR"], q["TI"], q["TE"], t["T1"], t["T2"], t["PD"], fs, fat)
        elif seq == "bSSFP":
            s = phys["bssfp_signal"](q["TR"], q["FA"], t["T1"], t["T2"], t["PD"])
            if fs and fat:
                s *= 0.05
        elif seq == "DIR":
            s = phys["dir_signal"](q["TR"], q["TI1"], q["TI2"], q["TE"], t["T1"], t["T2"], t["PD"])
            if fs and fat:
                s *= 0.05
        elif seq == "DWI":
            s = phys["dwi_signal"](q["TR"], q["TE"], q["b"], t["T1"], t["T2"], t["PD"], t["ADC"])
            if fs and fat:
                s *= 0.05
        elif seq == "MPRAGE":
            s = phys["mprage_signal"](q["TR"], q["TI"], q["TE"], q["FA"], t["T1"], t["T2s"], t["PD"])
            if fs and fat:
                s *= 0.05
        else:
            s = phys["epi_signal"](q["TR"], q["TE"], t["T1"], t["T2s"], t["PD"])
        out[name] = float(s)
    return out


DEF = dict(TR=2000, TE=30, TI=0, TI1=0, TI2=0, FA=90, b=0, ETL=1, NEX=1, BW=200, fovRead=400, fovPhase=400,
           freqMatrix=256, phaseMatrix=256, sliceMm=5, nPartitions=1, fatSat=False, pfFraction=1.0)
scenarios = [
    ("FSE", "3.0T", dict(TR=4000, TE=100, ETL=16)),
    ("FSE", "0.5T", dict(TR=600, TE=15, ETL=4, fatSat=True)),
    ("FSE", "3.0T", dict(TR=4000, TE=80, ETL=16, NEX=4, BW=100, pfFraction=0.75, sliceMm=3, freqMatrix=320)),
    ("GRE", "3.0T", dict(TR=700, TE=25, FA=25, phaseMatrix=192)),
    ("GRE", "1.5T", dict(TR=5, TE=7, FA=10, fatSat=True, pfFraction=0.625, fovRead=300, fovPhase=250)),
    ("FLAIR", "3.0T", dict(TR=9000, TE=90, TI=2500, ETL=16)),
    ("FLAIR", "7.0T", dict(TR=9000, TE=90, TI=2900, ETL=16, fatSat=True)),
    ("STIR", "1.5T", dict(TR=3000, TE=60, TI=150, ETL=8, phaseMatrix=224)),
    ("bSSFP", "3.0T", dict(TR=5, FA=50)),
    ("bSSFP", "0.064T", dict(TR=10, FA=70, fatSat=True)),
    ("DIR", "3.0T", dict(TR=8000, TE=25, TI1=3400, TI2=800, ETL=8)),
    ("DWI", "3.0T", dict(TR=5000, TE=80, b=1000, freqMatrix=128, phaseMatrix=128, NEX=2, BW=250)),
    ("DWI", "3.0T", dict(TR=5000, TE=80, b=3000, fatSat=True)),
    ("MPRAGE", "3.0T", dict(TR=2300, TE=3, TI=900, FA=9, nPartitions=176, sliceMm=1.0)),
    ("MPRAGE", "3.0T", dict(TR=2300, TE=3, TI=900, FA=9, nPartitions=256, sliceMm=1.0, fatSat=True)),
    ("EPI (single-shot)", "3.0T", dict(TR=2000, TE=30, freqMatrix=128, phaseMatrix=128, BW=250, pfFraction=0.75)),
    ("EPI (single-shot)", "11.7T", dict(TR=2000, TE=15, freqMatrix=128, phaseMatrix=128)),
]
for seq, field, over in scenarios:
    q = {**DEF, **over}
    is_3d = seq == "MPRAGE"
    base = base_signals(seq, field, q)
    ns = dict(phys)
    ns.update(base_signals=base, FOV_read=q["fovRead"], FOV_phase=q["fovPhase"], freq_matrix=q["freqMatrix"],
              phase_matrix=q["phaseMatrix"], slice_mm=q["sliceMm"], NEX=q["NEX"], BW=q["BW"], is_3d=is_3d,
              Npartitions=q["nPartitions"], pf_fraction=q["pfFraction"],
              _noise_ref_scaled=phys["NOISE_REF"] / tables["FIELD_SNR_SCALE"][field])
    exec(pipeline, ns)
    golden["pipeline"].append({
        "seq": seq, "field": field, "params": q, "baseSignals": base,
        "signals": ns["signals"], "snrs": {k: float(v) for k, v in ns["snrs"].items()},
        "noiseFloor": float(ns["noise_floor"]), "voxelVol": float(ns["voxel_vol"]), "volScale": float(ns["_vol_scale"]),
        "scanSec": float(phys["calc_scan_time"](q["TR"], q["phaseMatrix"], q["ETL"], q["NEX"], seq, q["nPartitions"])
                         * q["pfFraction"]),
    })

with open(os.path.join(OUT_DIR, "golden.json"), "w", encoding="utf-8", newline="\n") as f:
    json.dump(golden, f)
print({k: len(v) for k, v in golden.items()}, "tables:", list(tables))
