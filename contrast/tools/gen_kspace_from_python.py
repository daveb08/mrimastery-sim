"""One-time provenance script for the k-space visualiser: generate contrast/kspace_golden.json and
contrast/inferno.js.

The fill rules below are copied verbatim from the module-level k-space block of the original
MRI_Simulator/app.py (it is inline Streamlit code, not a function, so it cannot be imported). The original used one
N for both axes; here each axis gets its own N (the acquired frequency and phase matrices) and the same rule.
The inferno colour map is matplotlib's, sampled at 256 levels.

Run:   python <path>/gen_kspace_from_python.py
"""
import json
import os

import matplotlib

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def _ks_centric_rows(N: int, n_lines: int) -> list:
    """First n_lines row indices in FSE centric order (ky=0 first, outward)."""
    centre = N // 2
    order = [centre]
    for d in range(1, N):
        if len(order) >= n_lines:
            break
        if centre + d < N:
            order.append(centre + d)
        if len(order) >= n_lines:
            break
        if centre - d >= 0:
            order.append(centre - d)
    return order[:n_lines]


def ky_rows(N, pct, region, centric):
    _n_ky = max(1, round(N * (pct / 100)))
    if region == "Center":
        if centric:
            return _ks_centric_rows(N, _n_ky)
        _ky_ctr = N // 2
        _ky_half_below = _n_ky // 2
        _ky_half_above = _n_ky - _ky_half_below
        return list(range(max(0, _ky_ctr - _ky_half_below), min(N, _ky_ctr + _ky_half_above)))
    if centric:
        _ky_inner = set(_ks_centric_rows(N, N - _n_ky))
        return sorted(set(range(N)) - _ky_inner)
    _ky_top = _n_ky // 2
    _ky_bot = _n_ky - _ky_top
    return list(range(0, _ky_top)) + list(range(N - _ky_bot, N))


def kx_cols(N, pct, region):
    _n_kx = max(1, round(N * (pct / 100)))
    if region == "Center":
        _kx_ctr = N // 2
        _kx_half_below = _n_kx // 2
        _kx_half_above = _n_kx - _kx_half_below
        return list(range(max(0, _kx_ctr - _kx_half_below), min(N, _kx_ctr + _kx_half_above)))
    _kx_left = _n_kx // 2
    _kx_right = _n_kx - _kx_left
    return list(range(0, _kx_left)) + list(range(N - _kx_right, N))


golden = {"rows": [], "cols": []}
for N in (64, 128, 224, 256, 320):
    for pct in (1, 5, 10, 25, 33, 50, 67, 75, 99, 100):
        for region in ("Center", "Edges"):
            for centric in (False, True):
                golden["rows"].append({"N": N, "pct": pct, "region": region, "centric": centric,
                                       "rows": ky_rows(N, pct, region, centric)})
            golden["cols"].append({"N": N, "pct": pct, "region": region, "cols": kx_cols(N, pct, region)})

with open(os.path.join(OUT_DIR, "kspace_golden.json"), "w", encoding="utf-8", newline="\n") as f:
    json.dump(golden, f, separators=(",", ":"))

cmap = matplotlib.colormaps["inferno"]
lut = [round(c * 255) for i in range(256) for c in cmap(i / 255)[:3]]
with open(os.path.join(OUT_DIR, "inferno.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("// GENERATED by tools/gen_kspace_from_python.py: matplotlib's inferno colour map, 256 RGB triples.\n")
    f.write(f"export const INFERNO = new Uint8Array({json.dumps(lut)});\n")
print(len(golden["rows"]), "row cases,", len(golden["cols"]), "column cases")
